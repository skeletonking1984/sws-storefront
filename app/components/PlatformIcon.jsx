const IMAGE_ICONS = {
  Throne: '/platform-logos/throne.svg',
  StreamElements: '/platform-logos/streamelements.svg',
};

/**
 * Official brand mark for a supported platform, or a monogram badge for
 * names with no brand mark (VTuber is a format, not a brand).
 * @param {{platform: string}}
 */
export function PlatformIcon({platform}) {
  if (!brand.features.platformBadges) return null;
  const img = IMAGE_ICONS[platform];
  if (img) {
    return (
      <img
        className="platform-icon platform-icon-img"
        src={img}
        alt=""
        aria-hidden="true"
        width="16"
        height="16"
        loading="lazy"
        decoding="async"
      />
    );
  }
  const icon = ICONS[platform];
  if (icon) {
    return (
      <svg
        className="platform-icon"
        viewBox="0 0 24 24"
        xmlns="http://www.w3.org/2000/svg"
        aria-hidden="true"
        style={{'--platform-color': icon.color}}
      >
        <path d={icon.path} />
      </svg>
    );
  }
  return (
    <span className="platform-icon platform-icon-monogram" aria-hidden="true">
      {platform.slice(0, 2).toUpperCase()}
    </span>
  );
}
